CREATE TABLE IF NOT EXISTS watchlist (
    username VARCHAR(100) NOT NULL,
    code VARCHAR(6) NOT NULL,
    group_name VARCHAR(50) NOT NULL DEFAULT '기본',
    note VARCHAR(500) NOT NULL DEFAULT '',
    PRIMARY KEY (username, code),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS portfolio_position (
    username VARCHAR(100) NOT NULL,
    code VARCHAR(6) NOT NULL,
    quantity NUMERIC(20, 4) NOT NULL CHECK (quantity > 0),
    average_price NUMERIC(20, 4) NOT NULL CHECK (average_price > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (username, code)
);

CREATE TABLE IF NOT EXISTS portfolio_trade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    code VARCHAR(6) NOT NULL,
    trade_type VARCHAR(4) NOT NULL CHECK (trade_type IN ('BUY', 'SELL')),
    quantity NUMERIC(20, 4) NOT NULL CHECK (quantity > 0),
    price NUMERIC(20, 4) NOT NULL CHECK (price > 0),
    fee NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (fee >= 0),
    tax NUMERIC(20, 4) NOT NULL DEFAULT 0 CHECK (tax >= 0),
    realized_profit_loss NUMERIC(20, 4) NOT NULL DEFAULT 0,
    traded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    code VARCHAR(6) NOT NULL,
    condition_type VARCHAR(20) NOT NULL CHECK (condition_type IN ('PRICE_ABOVE', 'PRICE_BELOW', 'CHANGE_RATE_ABOVE', 'CHANGE_RATE_BELOW', 'RSI_ABOVE', 'RSI_BELOW', 'MACD_CROSS_UP', 'MACD_CROSS_DOWN')),
    threshold NUMERIC(20, 4),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_state BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (username, code, condition_type, threshold)
);

CREATE TABLE IF NOT EXISTS alert_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT REFERENCES alert_rule(id) ON DELETE SET NULL,
    username VARCHAR(100) NOT NULL,
    code VARCHAR(6) NOT NULL,
    condition_type VARCHAR(20) NOT NULL,
    observed_value NUMERIC(20, 4) NOT NULL,
    threshold NUMERIC(20, 4),
    triggered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE
);
