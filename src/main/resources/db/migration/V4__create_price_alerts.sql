CREATE TABLE alert_rule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(100) NOT NULL,
 code VARCHAR(6) NOT NULL, condition_type VARCHAR(20) NOT NULL CHECK (condition_type IN ('PRICE_ABOVE', 'PRICE_BELOW')),
 threshold NUMERIC(20,4) NOT NULL CHECK (threshold > 0), enabled BOOLEAN NOT NULL DEFAULT TRUE,
 last_state BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(username, code, condition_type, threshold)
);
CREATE INDEX idx_alert_rule_user ON alert_rule(username, enabled);
CREATE TABLE alert_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rule_id BIGINT REFERENCES alert_rule(id) ON DELETE SET NULL,
 username VARCHAR(100) NOT NULL, code VARCHAR(6) NOT NULL, condition_type VARCHAR(20) NOT NULL,
 observed_value NUMERIC(20,4) NOT NULL, threshold NUMERIC(20,4) NOT NULL,
 triggered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_alert_event_user ON alert_event(username, triggered_at DESC);
